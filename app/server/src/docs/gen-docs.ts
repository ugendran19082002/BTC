type Col = { table_name: string; column_name: string; data_type: string; udt_name: string; is_nullable: string; column_default: string | null; is_identity: string };

const UDT: Record<string, string> = {
  int2: 'smallint', int4: 'integer', int8: 'bigint', float4: 'real', float8: 'double precision',
  text: 'text', bool: 'boolean', jsonb: 'jsonb', numeric: 'numeric', varchar: 'varchar',
};

const typeOf = (c: Col) =>
  c.data_type === 'ARRAY' ? `${UDT[c.udt_name.slice(1)] ?? c.udt_name.slice(1)}[]`
    : c.data_type === 'character varying' ? 'varchar'
      : c.data_type;

/** `CREATE UNIQUE INDEX x ON public.t USING btree (a, b)` -> `x` unique (a, b). */
const indexOf = (name: string, def: string) => {
  const cols = /\((.*)\)(\s+WHERE\s+(.*))?$/.exec(def);
  const unique = /CREATE UNIQUE INDEX/.test(def) ? ' unique' : '';
  const where = cols?.[3] ? ` where ${cols[3]}` : '';
  return `\`${name}\`${unique} (${cols?.[1] ?? def})${where}`;
};

export async function renderSchema(): Promise<string> {
  await migrateEverything();
  const { rows } = await import('../db/pool.js');
  const cols = await rows<Col>(
    `SELECT c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default, c.is_identity
       FROM information_schema.columns c
       JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
      WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
      ORDER BY c.table_name, c.ordinal_position`,
  );
  const idx = await rows<{ tablename: string; indexname: string; indexdef: string }>(
    `SELECT tablename, indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' ORDER BY tablename, indexname`,
  );
  const cons = await rows<{ table_name: string; name: string; def: string }>(
    `SELECT cl.relname AS table_name, co.conname AS name, pg_get_constraintdef(co.oid) AS def
       FROM pg_constraint co
       JOIN pg_class cl ON cl.oid = co.conrelid
       JOIN pg_namespace n ON n.oid = cl.relnamespace
      WHERE n.nspname = 'public' AND co.contype IN ('f', 'c')
      ORDER BY cl.relname, co.conname`,
  );
  const migrations = await rows<{ id: string }>('SELECT id FROM public.schema_migrations ORDER BY id');

  const tables = [...new Set(cols.map((c) => c.table_name))];
  const byArea = new Map<string, string[]>();
  for (const { id } of migrations) {
    const area = id.replace(/-\d{3}-.*$/, '');
    byArea.set(area, [...(byArea.get(area) ?? []), id]);
  }

  const out: string[] = [
    HEADER,
    '',
    '# Database schema',
    '',
    'The desk\'s PostgreSQL database as a fresh deploy creates it: every table in `public`, read back from',
    'the catalogue after every store\'s migrations have run. What each table is *for*, and why it is shaped',
    'the way it is, is in [database.md](database.md).',
    '',
    `${tables.length} tables, ${migrations.length} migrations.`,
    '',
    '## Migrations applied',
    '',
    '| Area | Migrations |',
    '|---|---|',
    ...[...byArea].map(([a, ids]) => `| ${a} | ${ids.map((i) => `\`${i}\``).join(', ')} |`),
    '',
    '## Tables',
    '',
    tables.map((t) => `[\`${t}\`](#${t})`).join(' · '),
    '',
  ];
  for (const t of tables) {
    out.push(`### ${t}`, '', '| Column | Type | Null | Default |', '|---|---|---|---|');
    for (const c of cols.filter((c) => c.table_name === t)) {
      const dflt = c.is_identity === 'YES' ? 'identity' : c.column_default ? `\`${cell(c.column_default)}\`` : '';
      out.push(`| \`${c.column_name}\` | ${typeOf(c)} | ${c.is_nullable === 'YES' ? 'yes' : ''} | ${dflt} |`);
    }
    const keys = [
      ...idx.filter((i) => i.tablename === t).map((i) => indexOf(i.indexname, i.indexdef)),
      ...cons.filter((c) => c.table_name === t).map((c) => `\`${c.name}\` ${c.def}`),
    ];
    if (keys.length) out.push('', ...keys.map((k) => `- ${cell(k)}`));
    out.push('');
  }
  return out.join('\n');
}

