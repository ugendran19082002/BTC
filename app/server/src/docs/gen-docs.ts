/**
 * Markdown files the link check covers: the front door and everything under
 * docs/ but the history, which records links as they were.
 */
export const linkedPages = (files: readonly string[] = repoFiles()) =>
  files.filter((f) => f === 'README.md'
    || (f.startsWith('docs/') && f.endsWith('.md') && !f.startsWith('docs/history/')));

/**
 * Relative links that point at nothing. External links, anchors within the
 * page and links inside code spans or fences are not checked.
 */
export function brokenLinks(files: readonly string[] = repoFiles()): string[] {
  const broken: string[] = [];
  for (const page of linkedPages(files)) {
    const text = readFileSync(join(ROOT, page), 'utf8')
      .replace(/```[\s\S]*?```/g, '')
      .replace(/`[^`\n]*`/g, '');
    for (const m of text.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
      const target = m[1]!;
      if (/^[a-z]+:/i.test(target) || target.startsWith('#')) continue;
      const path = decodeURIComponent(target.split('#')[0]!);
      if (!existsSync(join(ROOT, posix.dirname(page), path))) broken.push(`${page} -> ${target}`);
    }
  }
  return broken;
}

/**
 * `docs/<name>.md` named in code or config, where no such page exists.
 * `<rev>:docs/<name>.md` -- a page in git history -- is allowed.
 *
 * The dated history and the research reports are left out: they record what
 * was true when they were written, including pages that have since moved.
 */
export function brokenDocMentions(files: readonly string[] = repoFiles()): string[] {
  const out: string[] = [];
  const TEXT = /\.(ts|tsx|js|mjs|py|sh|yml|yaml|conf|md|css|php|service)$|(^|\/)Dockerfile[^/]*$/;
  for (const f of files) {
    if (!TEXT.test(f) || f.startsWith('docs/history/') || f.startsWith('research/')) continue;
    const text = readFileSync(join(ROOT, f), 'utf8');
    for (const m of text.matchAll(/\bdocs\/[A-Za-z0-9_./-]+\.md\b/g)) {
      // `git show <rev>:docs/x.md` names a page in history, on purpose.
      if (text[m.index! - 1] === ':') continue;
      if (!existsSync(join(ROOT, m[0]))) out.push(`${f} -> ${m[0]}`);
    }
  }
  return [...new Set(out)];
}

