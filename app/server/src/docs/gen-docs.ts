type EnvUse = { name: string; where: string[] };

/** `process.env.X` and `process.env['X']` across the server's source. */
export function serverEnv(files: readonly string[] = repoFiles()): EnvUse[] {
  const uses = new Map<string, Set<string>>();
  // Not this file: its own comments name the pattern it looks for.
  const src = files.filter((f) => f.startsWith('app/server/src/') && f.endsWith('.ts') && !f.startsWith('app/server/src/docs/'));
  for (const f of src) {
    const text = readFileSync(join(ROOT, f), 'utf8');
    for (const m of text.matchAll(/process\.env(?:\.([A-Z][A-Z0-9_]*)|\[['"]([A-Z][A-Z0-9_]*)['"]\])/g)) {
      const name = m[1] ?? m[2]!;
      uses.set(name, (uses.get(name) ?? new Set()).add(f));
    }
  }
  return [...uses].map(([name, where]) => ({ name, where: [...where].sort() })).sort((a, b) => a.name.localeCompare(b.name));
}

/** `${X}` / `${X:-...}` in the compose file, and every key in deploy/.env.example. */
export function deployEnv(): EnvUse[] {
  const uses = new Map<string, Set<string>>();
  const add = (name: string, where: string) => uses.set(name, (uses.get(name) ?? new Set()).add(where));
  const compose = 'deploy/docker-compose.yml';
  for (const m of readFileSync(join(ROOT, compose), 'utf8').matchAll(/\$\{([A-Z][A-Z0-9_]*)/g)) add(m[1]!, compose);
  const example = 'deploy/.env.example';
  for (const m of readFileSync(join(ROOT, example), 'utf8').matchAll(/^([A-Z][A-Z0-9_]*)=/gm)) add(m[1]!, example);
  return [...uses].map(([name, where]) => ({ name, where: [...where].sort() })).sort((a, b) => a.name.localeCompare(b.name));
}

export function renderEnvironment(server = serverEnv(), deploy = deployEnv()): string {
  const example = readFileSync(join(ROOT, 'app/server/.env.example'), 'utf8');
  const inExample = (n: string) => new RegExp(`^#?\\s*${n}=`, 'm').test(example);
  const note = (n: string) => {
    const s = ENV_NOTES[n];
    if (!s) throw new Error(`docs: no note for environment variable ${n} -- add one to ENV_NOTES in app/server/src/docs/gen-docs.ts`);
    return s;
  };
  const files = (ws: string[]) => ws.map((w) => `[${posix.basename(w)}](${fromReference(w)})`).join(', ');
  return [
    HEADER,
    '',
    '# Environment',
    '',
    'Every environment variable the code reads, found by scanning for it. The API reads its own once, at',
    'start (`app/server/src/config.ts` and the modules listed), from `app/server/.env` under compose; the',
    'deploy variables are read by docker compose and the scripts from `deploy/.env`.',
    '',
    '## The API process',
    '',
    '| Variable | Read in | In `app/server/.env.example` | What it does |',
    '|---|---|---|---|',
    ...server.map((e) => `| \`${e.name}\` | ${files(e.where)} | ${inExample(e.name) ? 'yes' : '**no**'} | ${cell(note(e.name))} |`),
    '',
    '## Compose and the deploy scripts',
    '',
    '| Variable | Read in | What it does |',
    '|---|---|---|',
    ...deploy.map((e) => `| \`${e.name}\` | ${files(e.where)} | ${cell(note(e.name))} |`),
    '',
  ].join('\n');
}

