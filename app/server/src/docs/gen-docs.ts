/**
 * Every file git knows about or would add, that is still on disk.
 *
 * Untracked-but-not-ignored files count, so a new module shows up before its
 * first commit and the test says so while the change is still in hand.
 */
export function repoFiles(): string[] {
  const out = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], {
    cwd: ROOT, encoding: 'utf8',
  });
  return [...new Set(out.split('\0').filter(Boolean))]
    .filter((f) => existsSync(join(ROOT, f)))
    .sort();
}

const isTest = (f: string) =>
  /\.test\.(ts|tsx|js|mjs)$/.test(f) || /(^|\/)tests?\//.test(f) || /(^|\/)test_[^/]+\.py$/.test(f);

const SKIPPED_EXT = new Set(['.png', '.jpg', '.jpeg', '.gif', '.ico', '.svg', '.webp', '.woff', '.woff2', '.ttf']);
const skipped = (f: string) =>
  SKIPPED_EXT.has(extname(f).toLowerCase())
  || /(^|\/)package-lock\.json$/.test(f)
  || (GENERATED as readonly string[]).includes(f);

/** The first sentence of a paragraph, capped for a table cell. */
export function firstSentence(paragraph: string): string {
  const text = paragraph.replace(/\s+/g, ' ').trim();
  if (!text) return '';
  const m = /^(.*?[.!?])(?=\s+[A-Z(`"*_\[]|\s*$)/.exec(text);
  const s = (m?.[1] ?? text).trim();
  return s.length > 200 ? `${s.slice(0, 197).trimEnd()}...` : s;
}

/** The first paragraph of a run of comment lines, markers stripped. */
function paragraphOf(lines: string[]): string {
  const out: string[] = [];
  for (const raw of lines) {
    const l = raw
      .replace(/^\s*(\/\*\*?|\*\/|\*|\/\/+|#+!?|""")\s?/, '')
      .replace(/\s*(\*\/|""")\s*$/, '');
    if (!l.trim()) {
      if (out.length) break;
      continue;
    }
    out.push(l.trim());
  }
  return out.join(' ');
}

/**
 * A code file's header comment, if it has one.
 *
 * This codebase puts a file's docblock after its imports, often directly above
 * the first declaration. So, before the first function or class: the first
 * comment that stands on its own (a blank line or another comment after it),
 * else the longest block of three lines or more (two for `//` lines). A comment
 * directly above a function or class documents that declaration, not the file
 * -- quoting it as the file's purpose would be a confident wrong answer --
 * unless it is the only one the file has, or the first it exports.
 */
function codeHeader(text: string): string {
  const lines = text.split('\n');
  const DECL = /^(export\s+)?(default\s+)?(async\s+)?(function|class)\b/;
  let i = 0;
  let inImport = false;
  let best: { size: number; p: string } | null = null;
  while (i < lines.length && i < 120) {
    const t = lines[i]!.trim();
    if (inImport) {
      if (/from\s+['"][^'"]+['"];?\s*$/.test(t) || /^\}\s*;?$/.test(t)) inImport = false;
      i++;
      continue;
    }
    if (DECL.test(t)) break;
    if (/^import\b/.test(t)) {
      if (!/;\s*$/.test(t) && !/from\s+['"]/.test(t) && !/^import\s+['"]/.test(t)) inImport = true;
      i++;
      continue;
    }
    const block = t.startsWith('/*');
    const line = t.startsWith('//');
    if (!block && !line) { i++; continue; }
    const start = i;
    if (block) {
      while (i < lines.length && !lines[i]!.includes('*/')) i++;
      i++;
    } else {
      while (i < lines.length && lines[i]!.trim().startsWith('//')) i++;
    }
    const next = lines[i]?.trim() ?? '';
    const standsAlone = next === '' || next.startsWith('/*') || next.startsWith('//');
    const size = i - start;
    const p = paragraphOf(lines.slice(start, i));
    if (!p || /^(eslint|@ts-|prettier)/i.test(p)) continue;
    if (standsAlone) return p;
    // Attached to a declaration: a candidate only if it is long, and not a
    // function's or a class's own doc. The longest wins -- a file's docblock is
    // nearly always bigger than the one-paragraph note on a constant beside it.
    const long = block ? size >= 3 : size >= 2;
    // The one function or class a module holds, or the first one it exports
    // (a component file's component): its doc, at length, is the module's.
    const onlyDecl = DECL.test(next)
      && (lines.filter((l) => DECL.test(l)).length === 1 || /^export\s/.test(next));
    if (long && (!DECL.test(next) || onlyDecl) && size > (best?.size ?? 0)) best = { size, p };
  }
  return best?.p ?? '';
}

/** Leading `#` comments, after a shebang. */
function hashHeader(text: string): string {
  const lines = text.split('\n');
  const out: string[] = [];
  for (const raw of lines) {
    const t = raw.trim();
    // A shebang, and parser directives (`# syntax=...`) are not prose.
    if (t.startsWith('#!') || /^#\s*(syntax|escape|check)=/.test(t)) continue;
    if (!t.startsWith('#')) {
      if (out.length || t !== '') break;
      continue;
    }
    out.push(t);
  }
  return paragraphOf(out);
}

/** A module docstring, or leading comments. */
function pyHeader(text: string): string {
  const m = /^\s*(?:#[^\n]*\n\s*)*(?:"""|''')([\s\S]*?)(?:"""|''')/.exec(text);
  if (m) return paragraphOf(m[1]!.split('\n'));
  return hashHeader(text);
}

/** What a file is for, in one sentence, from the file itself. Empty when it does not say. */
export function summaryOf(file: string, text: string): string {
  const ext = extname(file).toLowerCase();
  const name = posix.basename(file);
  let p = '';
  if (['.ts', '.tsx', '.js', '.mjs', '.cjs', '.css', '.php'].includes(ext)) p = codeHeader(text);
  else if (ext === '.py') p = pyHeader(text);
  else if (['.sh', '.yml', '.yaml', '.toml', '.conf', '.service'].includes(ext) || name.startsWith('Dockerfile')
    || name.endsWith('.example') || name.startsWith('.')) p = hashHeader(text);
  else if (ext === '.md') p = /^#\s+(.+)$/m.exec(text)?.[1] ?? '';
  else if (ext === '.txt') p = text.split('\n').find((l) => l.trim() !== '')?.trim() ?? '';
  // JSON takes no comments: say what kind of file it is, from its name.
  else if (ext === '.json') {
    p = name === 'package.json' ? `npm package: ${(JSON.parse(text) as { name?: string }).name ?? 'unnamed'}, its scripts and dependencies.`
      : /^tsconfig/.test(name) ? 'TypeScript compiler settings.'
        : name === 'knip.json' ? 'knip settings: the entry points it cannot find by itself.'
          : 'JSON settings.';
  } else if (ext === '.html') p = /<title>([^<]*)<\/title>/.exec(text)?.[1] ? `The page shell: "${/<title>([^<]*)<\/title>/.exec(text)![1]}".` : '';
  return firstSentence(p);
}

const cell = (s: string) => s.replace(/\|/g, '\\|');

/** A link from a page in docs/reference/ to a repo path. */
const fromReference = (repoPath: string) => posix.relative('docs/reference', repoPath).replace(/ /g, '%20');

export function renderFiles(files: readonly string[] = repoFiles()): string {
  const listed = files.filter((f) => !isTest(f) && !skipped(f));
  const tests = files.filter(isTest);

  const byDir = new Map<string, string[]>();
  for (const f of listed) {
    const d = posix.dirname(f);
    byDir.set(d, [...(byDir.get(d) ?? []), f]);
  }
  const testsByArea = new Map<string, number>();
  for (const f of tests) {
    const area = f.split('/').slice(0, 2).join('/');
    testsByArea.set(area, (testsByArea.get(area) ?? 0) + 1);
  }

  const out: string[] = [
    HEADER,
    '',
    '# Files',
    '',
    'Every source, config and script file in the repository, with the first sentence of its own header',
    'comment. A dash means the file has no header comment -- the fix is to write one, not to edit this page.',
    '',
    `${listed.length} files listed, ${tests.length} test files counted below, images and lockfiles left out.`,
    '',
    '## Test files',
    '',
    '| Area | Test files |',
    '|---|---:|',
    ...[...testsByArea].sort(([a], [b]) => a.localeCompare(b)).map(([a, n]) => `| \`${a}\` | ${n} |`),
    '',
  ];
  for (const [dir, fs] of [...byDir].sort(([a], [b]) => a.localeCompare(b))) {
    out.push(`## \`${dir === '.' ? '(root)' : `${dir}/`}\``, '', '| File | What it is |', '|---|---|');
    for (const f of fs) {
      const summary = summaryOf(f, readFileSync(join(ROOT, f), 'utf8'));
      out.push(`| [${cell(posix.basename(f))}](${fromReference(f)}) | ${summary ? cell(summary) : '--'} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

// ------------------------------------------------------------------ API

export type RouteRow = { method: string; url: string; auth: string; file: string; what: string };

const ROUTE_FILE = /(app\/server\/src\/http\/routes\/[\w.-]+\.ts):(\d+)/;

/** The comment directly above a line, first sentence. */
function commentAbove(lines: readonly string[], lineNo: number): string {
  let i = lineNo - 2;
  if (i < 0) return '';
  const end = i;
  const t = lines[i]!.trim();
  if (t.startsWith('//')) {
    while (i >= 0 && lines[i]!.trim().startsWith('//')) i--;
    return firstSentence(paragraphOf(lines.slice(i + 1, end + 1)));
  }
  if (t.endsWith('*/')) {
    while (i >= 0 && !lines[i]!.includes('/*')) i--;
    return firstSentence(paragraphOf(lines.slice(i, end + 1)));
  }
  return '';
}

const SESSION: Record<string, string> = {
  public: 'none',
  totp: 'password step',
  setup: 'two-step setup',
  full: 'signed in',
};

/**
 * Every route, as Fastify registered it.
 *
 * Read from the app itself rather than parsed out of the source, so a route
 * added by any means is listed; the source line is taken from the stack at
 * registration only to find the comment that describes it.
 */
export async function collectRoutes(): Promise<RouteRow[]> {
  const { buildApp, routeAuthLevel } = await import('../http/app.js');
  const seen: RouteRow[] = [];
  const texts = new Map<string, string[]>();
  const app = await buildApp({
    onRoute: (r: RouteOptions) => {
      const methods = (Array.isArray(r.method) ? r.method : [r.method]).filter((m) => m !== 'HEAD');
      const at = ROUTE_FILE.exec(new Error().stack ?? '');
      const file = at?.[1] ?? '';
      let what = '';
      if (at) {
        if (!texts.has(file)) texts.set(file, readFileSync(join(ROOT, file), 'utf8').split('\n'));
        what = commentAbove(texts.get(file)!, Number(at[2]));
      }
      for (const method of methods) {
        seen.push({ method, url: r.url, auth: routeAuthLevel(r.url, r.config), file, what });
      }
    },
  });
  await app.ready();
  await app.close();
  return seen;
}

export function renderApi(routes: readonly RouteRow[]): string {
  const byFile = new Map<string, RouteRow[]>();
  for (const r of routes) byFile.set(r.file, [...(byFile.get(r.file) ?? []), r]);
  const out: string[] = [
    HEADER,
    '',
    '# HTTP API',
    '',
    'Every route the API registers, read from the Fastify app itself. All answer JSON under `/api`, behind',
    'one session cookie; the Session column is the sign-in stage a route needs (`routeAuthLevel` in',
    '`http/app.ts` -- a route is closed unless it says otherwise). Every POST, PUT, PATCH and DELETE must',
    'also carry an `Origin` or `Referer` naming the desk\'s own host.',
    '',
    'What: the first sentence of the comment directly above the route. A dash means there is none.',
    '',
    `${routes.length} routes.`,
    '',
  ];
  for (const [file, rs] of [...byFile].sort(([a], [b]) => a.localeCompare(b))) {
    out.push(`## [${posix.basename(file) || '(unknown file)'}](${fromReference(file)})`, '');
    out.push('| Method | Path | Session | What |', '|---|---|---|---|');
    for (const r of [...rs].sort((a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method))) {
      out.push(`| ${r.method} | \`${r.url}\` | ${SESSION[r.auth] ?? r.auth} | ${r.what ? cell(r.what) : '--'} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

